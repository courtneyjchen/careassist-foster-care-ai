    "# Target encoding (FIPSCODE) + one-hot encoding\n",
    "\n",
    "if 'FIPSCODE' in df.columns:\n",
    "    gm = df['DISRUPTION'].mean()\n",
    "    smoothing = 100\n",
    "    st = df.groupby('FIPSCODE')['DISRUPTION'].agg(['mean','count'])\n",
    "    st['smoothed'] = (st['count']*st['mean'] + smoothing*gm) / (st['count'] + smoothing)\n",
    "    df['state_disruption_rate'] = df['FIPSCODE'].map(st['smoothed']).fillna(gm).astype(np.float32)\n",
    "    q33 = df['state_disruption_rate'].quantile(0.33)\n",
    "    q66 = df['state_disruption_rate'].quantile(0.66)\n",
    "    df['state_risk_low']  = (df['state_disruption_rate'] <= q33).astype(np.int8)\n",
    "    df['state_risk_high'] = (df['state_disruption_rate'] >= q66).astype(np.int8)\n",
    "    df.drop(columns=['FIPSCODE'], inplace=True)\n",
    "    print('Target-encoded FIPSCODE')\n",
    "\n",
    "if 'FISCAL_YEAR' in df.columns:\n",
    "    df.drop(columns=['FISCAL_YEAR'], inplace=True)\n",
