    "    df_raw['age_at_removal'] = np.nan\n",
    "\n",
    "# Disability indicators\n",
    "disability_cols = ['MR', 'VISHEAR', 'PHYDIS', 'EMOTDIST', 'OTHERMED']\n",
    "for c in disability_cols:\n",
    "    if c in df_raw.columns:\n",
    "        df_raw[c] = df_raw[c].fillna(0).clip(0, 1).astype(np.int8)\n",
    "    else:\n",
    "        df_raw[c] = np.int8(0)\n",
    "df_raw['has_disability'] = df_raw[disability_cols].max(axis=1)\n",
    "df_raw['has_clinical_disability'] = (df_raw['CLINDIS'] == 1).astype(np.int8) if 'CLINDIS' in df_raw.columns else np.int8(0)\n",
    "df_raw['has_behavioral'] = df_raw['CHBEHPRB'].fillna(0).clip(0, 1).astype(np.int8) if 'CHBEHPRB' in df_raw.columns else np.int8(0)\n",
