    "df_raw['los_current_setting'] = pd.to_numeric(df_raw['SETTINGLOS'], errors='coerce').astype(np.float32) if 'SETTINGLOS' in df_raw.columns else np.float32(np.nan)\n",
    "df_raw['los_latest_removal'] = pd.to_numeric(df_raw['LATREMLOS'], errors='coerce').astype(np.float32) if 'LATREMLOS' in df_raw.columns else np.float32(np.nan)\n",
    "df_raw['ever_adopted'] = df_raw['EVERADPT'].fillna(0).clip(0,1).astype(np.int8) if 'EVERADPT' in df_raw.columns else np.int8(0)\n",
    "df_raw['mandatory_removal'] = df_raw['MANREM'].fillna(0).clip(0,1).astype(np.int8) if 'MANREM' in df_raw.columns else np.int8(0)\n",
