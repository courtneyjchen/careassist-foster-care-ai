    "df_raw['age_x_disability'] = (age * df_raw['disability_severity']).astype(np.float32)\n",
    "df_raw['removals_x_disability'] = (tot_rem * df_raw['disability_severity']).astype(np.float32)\n",
    "df_raw['age_x_risk'] = (age * df_raw['removal_risk_score']).astype(np.float32)\n",
    "df_raw['age_x_behavioral'] = (age * df_raw['has_behavioral']).astype(np.float32)\n",
    "df_raw['removals_x_abuse'] = (tot_rem * df_raw['abuse_severity']).astype(np.float32)\n",
    "\n",
    "# Placement out (if available)\n",
    "if 'PLACEOUT' in df_raw.columns:\n",
    "    df_raw['place_out'] = df_raw['PLACEOUT'].where(df_raw['PLACEOUT'].isin([1,2,3,4,5,6,7,8]))\n",
